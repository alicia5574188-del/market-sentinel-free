export const hte31PostExitObservations = sqliteTable("hte31_post_exit_observations", {
  tradeId: text("trade_id").notNull(),
  horizonMinutes: integer("horizon_minutes").notNull(),
  dueAt: integer("due_at").notNull(),
  observedAt: integer("observed_at"),
  status: text("status", { enum: ["pending", "complete"] }).notNull().default("pending"),
  qualityStatus: text("quality_status", { enum: ["PENDING", "READY", "STALE", "UNAVAILABLE"] }).notNull().default("PENDING"),
  coveragePct: real("coverage_pct"),
  lastError: text("last_error"),
  retryCount: integer("retry_count").notNull().default(0),
  nextRetryAt: integer("next_retry_at"),
  price: real("price"),
  favorablePct: real("favorable_pct"),
  adversePct: real("adverse_pct"),
  favorableR: real("favorable_r"),
  adverseR: real("adverse_r"),
  candlesJson: text("candles_json").notNull().default("[]"),
}, (table) => [
  primaryKey({ columns: [table.tradeId, table.horizonMinutes] }),
  index("hte31_post_exit_due_idx").on(table.status, table.dueAt),
]);
